from pathlib import Path
import sys


BASE_DIR = Path(
    __file__
).resolve().parent


REQUIRED_FILES = [

    "app.py",

    "download_dataset.py",

    "train_model.py",

    "quantize_model.py",

    "prepare_runtime.py",

    "requirements.txt",

    "templates/index.html",

    "static/app.js",

    "static/style.css",

    "ml/dataset.py",

]


print()
print("=" * 60)
print("Healthy AI Project Verification")
print("=" * 60)
print()


missing = []


for filename in REQUIRED_FILES:

    path = (
        BASE_DIR
        / filename
    )

    if path.exists():

        print(
            "[OK] ",
            filename,
        )

    else:

        print(
            "[MISSING] ",
            filename,
        )

        missing.append(
            filename
        )


print()


if missing:

    print(
        "Verification failed."
    )

    print(
        "Missing files:",
        ", ".join(missing),
    )

    sys.exit(1)


print(
    "[OK] Project structure is complete."
)


model_path = (
    BASE_DIR
    / "model"
    / "healthy_ai_int8.onnx"
)


classes_path = (
    BASE_DIR
    / "model"
    / "class_names.json"
)


if model_path.exists():

    print(
        "[OK] INT8 ONNX model found."
    )

else:

    print(
        "[INFO] INT8 model not trained yet."
    )


if classes_path.exists():

    print(
        "[OK] Class names found."
    )

else:

    print(
        "[INFO] Class names will be generated by training."
    )


print()
print(
    "Verification finished."
)